// Derives, for every OpenAPI operation, a map of response paths -> binding field types.
// The widget binding validator uses it to check that a slot receives a value of the right type.
//
//   ImageUrls -> image, HistoricalDateDto -> historical-date, MoneyDto -> money,
//   uuid -> reference, date/date-time -> date, string/enum -> text, integer/number -> number,
//   boolean -> boolean, arrays -> list (items under "path[]").
//
// Usage: node scripts/generate-field-types.mjs [openapi.json] [out.ts]
import { readFileSync, writeFileSync } from 'node:fs'
import { SPECIAL, leafType } from './fieldTypeRules.mjs'

const input = process.argv[2] ?? '../backend/openapi/Artefacts.Api.json'
const output = process.argv[3] ?? 'src/api/fieldTypes.generated.ts'
const doc = JSON.parse(readFileSync(input, 'utf8'))
const schemas = doc.components?.schemas ?? {}

const MAX_DEPTH = 6

function refName(schema) {
  return schema?.$ref?.split('/').pop()
}

/** Removes the `null` alternative from nullable schemas. */
function unwrap(schema) {
  if (!schema) return schema
  for (const key of ['oneOf', 'anyOf']) {
    if (Array.isArray(schema[key])) {
      const nonNull = schema[key].filter((s) => s.type !== 'null')
      if (nonNull.length === 1) return unwrap(nonNull[0])
    }
  }
  if (Array.isArray(schema.type)) {
    const types = schema.type.filter((t) => t !== 'null')
    if (types.length === 1) return { ...schema, type: types[0] }
  }
  return schema
}

function walk(schema, path, out, depth) {
  schema = unwrap(schema)
  if (!schema || depth > MAX_DEPTH) return
  const name = refName(schema)
  if (name && SPECIAL[name]) {
    out[path] = SPECIAL[name]
    return
  }
  if (name) return walk(schemas[name], path, out, depth + 1)

  if (schema.enum || ['string', 'integer', 'number', 'boolean'].includes(schema.type)) return void (out[path] = leafType(schema))
  switch (schema.type) {
    case 'array':
      out[path + '[]'] = 'list'
      return walk(schema.items, path + '[]', out, depth + 1)
    case 'object':
      // A map with no fixed properties (e.g. names or descriptions keyed by language).
      if (!schema.properties && schema.additionalProperties) return void (out[path] = 'map')
      for (const [prop, propSchema] of Object.entries(schema.properties ?? {}))
        walk(propSchema, path ? `${path}.${prop}` : prop, out, depth + 1)
      return
  }
}

const result = {}
const operations = {}
for (const [route, methods] of Object.entries(doc.paths ?? {})) {
  for (const [method, op] of Object.entries(methods)) {
    if (!op?.operationId) continue
    operations[op.operationId] = { method: method.toUpperCase(), path: route }
    const response = op.responses?.['200'] ?? op.responses?.['201']
    const schema = response?.content?.['application/json']?.schema
    if (!schema) continue
    const fields = {}
    walk(schema, '', fields, 0)
    // An array response root is addressed as "[]".
    result[op.operationId] = Object.fromEntries(Object.entries(fields).sort(([a], [b]) => a.localeCompare(b)))
  }
}

const body =
  '// Generated by scripts/generate-field-types.mjs from the backend OpenAPI document. Do not edit.\n' +
  "import type { FieldType } from '../widgets/core/types'\n\n" +
  'export const responseFieldTypes = ' +
  JSON.stringify(result, null, 2) +
  ' as const satisfies Record<string, Record<string, FieldType>>\n\n' +
  'export type OperationId = keyof typeof responseFieldTypes\n\n' +
  '/** HTTP method and route template of every operation (used by endpoint data sources). */\n' +
  'export const operations = ' +
  JSON.stringify(operations, null, 2) +
  ' as const satisfies Record<string, { method: string; path: string }>\n'
writeFileSync(output, body)
console.log(`Wrote field types for ${Object.keys(result).length} operations to ${output}`)
